-- 1. Buat Tabel Data Barkot Harian
CREATE TABLE IF NOT EXISTS public.barkot_data (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tanggal DATE NOT NULL,                         -- Format: YYYY-MM-DD
    no_gud INTEGER NOT NULL,                       -- Nomor Gudang (misal: 107)
    grade TEXT,                                    -- Grade Tembakau
    barkot TEXT,                                   -- Nomor Barcode / Barkot
    kg NUMERIC,                                    -- Berat Kg
    is_done BOOLEAN DEFAULT FALSE,                 -- Status: TRUE jika sudah dibarkot
    done_at TIMESTAMP WITH TIME ZONE,              -- Waktu saat dicentang di lapangan
    created_at TIMESTAMP WITH TIME ZONE DEFAULT TIMEZONE('utc'::text, NOW()),
    
    CONSTRAINT unique_tanggal_nogud UNIQUE (tanggal, no_gud)
);

-- 2. Buat Index untuk performa pencarian kilat
CREATE INDEX IF NOT EXISTS idx_barkot_tanggal ON public.barkot_data (tanggal);
CREATE INDEX IF NOT EXISTS idx_barkot_nogud ON public.barkot_data (no_gud);

-- 3. Aktifkan Row Level Security (RLS) & Berikan Izin Akses Publik
ALTER TABLE public.barkot_data ENABLE ROW LEVEL SECURITY;

DROP POLICY IF EXISTS "Public Full Access Barkot" ON public.barkot_data;
CREATE POLICY "Public Full Access Barkot" 
ON public.barkot_data 
FOR ALL 
USING (true) 
WITH CHECK (true);

-- 4. Aktifkan Fitur Realtime
ALTER PUBLICATION supabase_realtime ADD TABLE public.barkot_data;

